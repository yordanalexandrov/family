import { describe, expect, it } from 'vitest';
import { findStepIngredients } from './step-ingredients';

/** Имената на намерените редове, за да чете тестът смисъла, не индексите. */
function found(text: string, names: readonly string[]): string[] {
  return findStepIngredients(text, names).map((index) => names[index] ?? '');
}

describe('findStepIngredients', () => {
  it('членувана форма на името: „лук“ в „Задуши с лука.“', () => {
    expect(
      findStepIngredients('Задуши с лука.', ['пилешко филе', 'лук', 'сол']),
    ).toEqual([1]);
  });

  it.each([
    ['Запържи лука до златисто.', 'лук'],
    ['Лукът трябва да омекне.', 'лук'],
    ['Добави доматите и разбъркай.', 'домат'],
    ['Нарежи два домата на кубчета.', 'домат'],
    ['Разбий яйцата с вилица.', 'яйце'],
    ['Счупи едно яйце в купата.', 'яйце'],
    ['Обели картофите.', 'картофи'],
    ['Нарежи чушките на ленти.', 'чушка'],
    ['Посоли със солта.', 'сол'],
    ['Пресей брашното в купа.', 'брашно'],
    ['Загрей олиото в тиган.', 'олио'],
    ['Натроши сиренето отгоре.', 'сирене'],
    ['Добави захарта и маслото.', 'захар'],
    ['Добави захарта и маслото.', 'масло'],
    ['Изплакни ориза.', 'ориз'],
    ['Настържи морковите.', 'морков'],
    ['Счукай чесъна.', 'чесън'],
    ['ДОМАТИТЕ се белят лесно.', 'домат'],
  ])('членувани и множествени форми: „%s“ ← „%s“', (text, name) => {
    expect(found(text, [name])).toEqual([name]);
  });

  it('име от няколко думи се хваща по последната дума', () => {
    expect(
      found('Нарежи филето на ивици.', ['пилешко филе', 'лук', 'сол']),
    ).toEqual(['пилешко филе']);
  });

  it('два реда с една последна дума: печели пълното име в текста', () => {
    const names = ['черен пипер', 'червен пипер', 'сол'];
    expect(found('Поръси с черен пипер.', names)).toEqual(['черен пипер']);
    expect(found('Добави червения пипер.', names)).toEqual(['червен пипер']);
    expect(found('Поръси с черния пипер.', names)).toEqual(['черен пипер']);
    expect(found('Подправи със сол и пипер.', names)).toEqual([
      'черен пипер',
      'червен пипер',
      'сол',
    ]);
  });

  it('ред само с последната дума и ред с пълно име: на мястото на пълното печели пълното', () => {
    const names = ['пипер', 'черен пипер'];
    expect(found('Поръси с черен пипер.', names)).toEqual(['черен пипер']);
    expect(found('Сложи пипер, после още черен пипер.', names)).toEqual([
      'пипер',
      'черен пипер',
    ]);
  });

  it.each([
    ['Сипи от лукчето.', 'лук'],
    ['Нарежи доматеното пюре.', 'домат'],
    ['Пролуката между тавите да е малка.', 'лук'],
    ['Добави ориза.', 'риз'],
  ])(
    'дума, която само започва или свършва с името, не е продукт: „%s“',
    (text, name) => {
      expect(found(text, [name])).toEqual([]);
    },
  );

  it('пред и след думата може да има препинателни знаци и цифри са граница', () => {
    expect(
      found('(лук), „доматите“; 2 яйца.', ['лук', 'домат', 'яйце']),
    ).toEqual(['лук', 'домат', 'яйце']);
  });

  it('цифра, залепена за думата, е граница: „2яйца“, „яйца2“', () => {
    expect(found('Разбий 2яйца.', ['яйце'])).toEqual(['яйце']);
    expect(found('Разбий яйца2.', ['яйце'])).toEqual(['яйце']);
  });

  it('стъпка без продукти: празен списък', () => {
    expect(
      found('Разбъркай сместа и остави да почине 10 мин.', [
        'пилешко филе',
        'лук',
        'сол',
      ]),
    ).toEqual([]);
  });

  it('само името, без синоними и местоимения: „зеленчуците“, „го“', () => {
    expect(
      found('Задуши зеленчуците и ги посоли.', ['тиквичка', 'морков']),
    ).toEqual([]);
  });

  it('ред, назован няколко пъти, се връща веднъж, по реда на редовете', () => {
    expect(
      findStepIngredients('Сол, лук и пак сол.', ['лук', 'пипер', 'сол']),
    ).toEqual([0, 2]);
  });

  it('име без букви не се търси', () => {
    expect(findStepIngredients('Добави 2 с.л.', ['', '2'])).toEqual([]);
  });
});
