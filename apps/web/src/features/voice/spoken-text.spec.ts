import { describe, expect, it } from 'vitest';
import { spokenText } from './spoken-text';

describe('spokenText', () => {
  it.each([
    ['Задуши 15 мин.', 'Задуши 15 минути.'],
    ['Печи 1 ч на 180°C.', 'Печи 1 час на 180 градуса.'],
    ['Остави 2 ч да втаса.', 'Остави 2 часа да втаса.'],
    ['Сложи 200 г сирене.', 'Сложи 200 грама сирене.'],
    ['Сложи 1 г сол.', 'Сложи 1 грам сол.'],
    ['Добави 250 гр. брашно.', 'Добави 250 грама брашно.'],
    ['Свари 10–15 мин', 'Свари 10–15 минути'],
    ['Задуши 1 мин', 'Задуши 1 минута'],
    ['Печи 1,5 ч', 'Печи 1,5 часа'],
    ['Загрей фурната на 200 °C', 'Загрей фурната на 200 градуса'],
    // С кирилско „С“, както често се пише.
    ['Загрей на 180°С.', 'Загрей на 180 градуса.'],
    ['Загрей на 1°C.', 'Загрей на 1 градус.'],
  ])('„%s“ → „%s“', (text, spoken) => {
    expect(spokenText(text)).toBe(spoken);
  });

  it.each([
    // Съкращенията са само след число, а думите, които започват така, не се пипат.
    'Нарежи гъбите на ч, после минути по-късно.',
    'Минимум 2 часа, 200 грама.',
    'Добави 1 ч.л. захар и 2 с.л. олио.',
    'Сложи мин. количество сол.',
  ])('„%s“ остава както е', (text) => {
    expect(spokenText(text)).toBe(text);
  });
});
