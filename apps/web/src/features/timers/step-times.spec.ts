import { describe, expect, it } from 'vitest';
import { findStepTimes } from './step-times';

/** Само смисълът: откъснатият текст, надписът и секундите (горната граница — за интервал). */
function times(text: string) {
  return findStepTimes(text).map(
    ({ start, end, label, seconds, maxSeconds }) => ({
      text: text.slice(start, end),
      label,
      seconds,
      ...(maxSeconds === undefined ? {} : { maxSeconds }),
    }),
  );
}

describe('findStepTimes', () => {
  it('минути в средата на текста', () => {
    expect(times('Пържи 15 мин до златисто.')).toEqual([
      { text: '15 мин', label: '15 мин', seconds: 900 },
    ]);
  });

  it.each([
    ['Запържи 30 сек.', '30 сек', 30],
    ['Вари 20 минути', '20 минути', 1200],
    ['Изпечи 1 минута от всяка страна', '1 минута', 60],
    ['Печи 2 ч на 160°', '2 ч', 7200],
    ['Задуши 1 час', '1 час', 3600],
    ['Остави 2 часа да втаса', '2 часа', 7200],
    ['Вари 45 секунди', '45 секунди', 45],
    ['Печи 40 МИН.', '40 МИН', 2400],
  ])('секунди, минути и часове: „%s“', (text, found, seconds) => {
    expect(times(text)).toEqual([{ text: found, label: found, seconds }]);
  });

  it('„половин час“', () => {
    expect(times('Задуши половин час под капак.')).toEqual([
      { text: 'половин час', label: 'половин час', seconds: 1800 },
    ]);
  });

  it.each([
    ['Печи 1 ч и 30 мин', '1 ч и 30 мин', 5400],
    ['Печи 1 час и 15 минути', '1 час и 15 минути', 4500],
    ['Печи 2 ч. 10 мин.', '2 ч. 10 мин', 7800],
    ['Бъркай 1 мин и 30 сек', '1 мин и 30 сек', 90],
  ])('съчетание е едно време: „%s“', (text, found, seconds) => {
    expect(times(text)).toEqual([{ text: found, label: found, seconds }]);
  });

  it.each([
    ['Печи 1,5 часа', '1,5 часа', 5400],
    ['Печи 1.5 ч', '1.5 ч', 5400],
    ['Вари 2,5 мин', '2,5 мин', 150],
  ])('десетична запетая или точка: „%s“', (text, found, seconds) => {
    expect(times(text)).toEqual([{ text: found, label: found, seconds }]);
  });

  it.each([
    ['Пържи 10–15 мин', '10–15 мин'],
    ['Пържи 10-15 мин', '10-15 мин'],
    ['Пържи 10 - 15 мин', '10 - 15 мин'],
  ])(
    'интервал брои до долната граница, надписан с „–“: „%s“',
    (text, found) => {
      expect(times(text)).toEqual([
        { text: found, label: '10–15 мин', seconds: 600, maxSeconds: 900 },
      ]);
    },
  );

  it('интервал в часове с десетична запетая', () => {
    expect(times('Печи 1–1,5 часа')).toEqual([
      {
        text: '1–1,5 часа',
        label: '1–1,5 часа',
        seconds: 3600,
        maxSeconds: 5400,
      },
    ]);
  });

  it.each([
    'Остави в хладилника една нощ.',
    'Мариновай 24 часа в хладилника.',
    'Мариновай 12–24 часа.',
    'Втаси 13 ч.',
  ])('над 12 часа не се предлага: „%s“', (text) => {
    expect(times(text)).toEqual([]);
  });

  it('точно 12 часа се предлага', () => {
    expect(times('Мариновай 12 часа')).toEqual([
      { text: '12 часа', label: '12 часа', seconds: 43200 },
    ]);
  });

  it('две времена в една стъпка са две отделни', () => {
    expect(times('Запържи 5 мин, после печи 40 мин на 180°.')).toEqual([
      { text: '5 мин', label: '5 мин', seconds: 300 },
      { text: '40 мин', label: '40 мин', seconds: 2400 },
    ]);
  });

  it.each([
    'Нарежи лука на ситно.',
    'Добави 2 чаши вода и 1 ч.л. сол.',
    'Сложи 200 г минерална вода.',
    'Нагрей фурната на 180°.',
    'Добави 1 ч. л. сода и 2 с.л. олио.',
    'Добави 0 мин.',
  ])('текст без време: „%s“', (text) => {
    expect(times(text)).toEqual([]);
  });
});
